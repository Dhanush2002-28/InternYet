import { jsPDF } from "jspdf";
import { organization } from "../../config/organization";
import { formatDate } from "../../utils/format";

export function generateCertificatePdf(student) {
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();

  doc.setDrawColor(26, 86, 219);
  doc.setLineWidth(2);
  doc.rect(28, 28, W - 56, H - 56);
  doc.setLineWidth(0.75);
  doc.rect(38, 38, W - 76, H - 76);
  doc.setFillColor(26, 86, 219);
  [
    [28, 28],
    [W - 28, 28],
    [28, H - 28],
    [W - 28, H - 28]
  ].forEach(([cx, cy]) => {
    doc.circle(cx, cy, 5, "F");
  });

  const cx = W / 2;
  let y = 118;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(96, 104, 116);
  doc.text(organization.name.toUpperCase(), cx, y, { align: "center", charSpace: 2 });
  y += 46;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(30);
  doc.setTextColor(23, 26, 32);
  doc.text("Certificate of Completion", cx, y, { align: "center" });
  y += 34;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(96, 104, 116);
  doc.text("This certificate is proudly presented to", cx, y, { align: "center" });
  y += 42;

  doc.setFont("helvetica", "italic");
  doc.setFontSize(26);
  doc.setTextColor(26, 86, 219);
  doc.text(student.name || "Student", cx, y, { align: "center" });
  doc.setDrawColor(214, 219, 226);
  doc.setLineWidth(0.75);
  doc.line(cx - 170, y + 10, cx + 170, y + 10);
  y += 38;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(12);
  doc.setTextColor(60, 66, 76);
  doc.text("for successfully completing the", cx, y, { align: "center" });
  y += 22;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(23, 26, 32);
  doc.text(organization.program, cx, y, { align: "center" });
  y += 24;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(60, 66, 76);
  const completedOn = student.internship?.completedAt || student.internship?.certificate?.issuedAt;
  doc.text(
    `Duration: ${organization.duration}   |   Completed on: ${formatDate(completedOn)}`,
    cx,
    y,
    { align: "center" }
  );
  y += 18;
  doc.text(
    `Certificate ID: ${student.internship?.certificate?.number || ""}`,
    cx,
    y,
    { align: "center" }
  );

  const certNumber = student.internship?.certificate?.number || "";
  const verifyOrigin = typeof window !== "undefined" ? window.location.origin : "";
  if (certNumber && verifyOrigin) {
    doc.setFontSize(8.5);
    doc.setTextColor(150, 156, 166);
    doc.text(`Verify this certificate at ${verifyOrigin}/verify?c=${certNumber}`, cx, y + 13, {
      align: "center"
    });
  }

  const sigY = H - 92;
  doc.setDrawColor(140, 146, 156);
  doc.setLineWidth(0.75);
  doc.line(cx - 190, sigY, cx - 55, sigY);
  doc.line(cx + 55, sigY, cx + 190, sigY);
  doc.setFontSize(10);
  doc.setTextColor(96, 104, 116);
  doc.text(student.internship?.certificate?.issuerName || "Program Mentor", cx - 122, sigY + 16, {
    align: "center"
  });
  doc.text("Program Mentor", cx - 122, sigY + 30, { align: "center" });
  doc.text(organization.signatoryName, cx + 122, sigY + 16, { align: "center" });
  doc.text(`${organization.signatoryTitle}, ${organization.name}`, cx + 122, sigY + 30, {
    align: "center"
  });

  doc.setFontSize(8.5);
  doc.setTextColor(150, 156, 166);
  doc.text(
    `System-generated by the ${organization.shortName} · ${organization.website}`,
    cx,
    H - 44,
    { align: "center" }
  );

  return doc;
}